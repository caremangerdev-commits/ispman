-- WHAT HAS TO CHANGE IN THE APP (NOT DONE — FOR THE NEXT PIECE OF WORK)
-- ===========================================================================
--
-- (a) lib/schema.ts — add a `bills` capability probe, so the app runs
--     unchanged until this migration is applied. Every other table added since
--     0003 follows this pattern; without it the first query rejects.
--
-- (b) app/actions/bulk.ts#billBatch — insert one row per customer billed,
--     inside the same step that updates carried_balance, sharing one run_id
--     generated by the caller. Open question below.
--
-- (c) app/actions/customers.ts#deleteCustomer — MUST be updated in the same
--     change. It clears dependents by hand (log, notifications_queue,
--     support_tickets, payments) before deleting the customer. `bills` has a
--     NOT NULL FK to customers, so without adding it to that list every
--     customer deletion starts failing with a foreign key violation. See the
--     retention question below before deciding HOW it is handled.
--
-- (d) lib/data/dashboard.ts — a real billed series: sum(amount) grouped by
--     period_start. The existing `recurring` series stays as it is; this is a
--     third line, not a replacement.
--
-- ===========================================================================
-- THREE THINGS TO DECIDE BEFORE THIS IS BUILT
-- ===========================================================================
--
-- (1) ATOMICITY. Writing a bill row and updating carried_balance are two
--     statements over PostgREST, which has no client-side transaction. A crash
--     between them leaves a charge with no record, or a record with no charge.
--     Options: a SECURITY DEFINER function doing both in one statement (adds a
--     second hand-run migration, makes billBatch a single RPC call), or accept
--     the window and reconcile from bills. The unique constraint makes the
--     second failure mode self-correcting on a re-run; the first is not.
--     RECOMMENDATION: the function. It also makes the guard atomic.
--
-- (2) RETENTION ON CUSTOMER DELETE. Financial history normally outlives the
--     customer record, but the FK above is NOT NULL and deleteCustomer expects
--     to clear dependents. Three ways:
--       - delete the bills too (simplest, matches how payments are treated
--         today, loses the money trail);
--       - ON DELETE SET NULL with a nullable customer_id plus a denormalised
--         customer_name (keeps totals correct, keeps the name readable);
--       - block deletion of a customer who has been billed.
--     This file assumes NOTHING and leaves the FK strict, because the choice
--     changes the column definition. It has to be settled before the table is
--     written to — changing it afterwards means migrating real rows.
--
-- (3) WHETHER last_billed_date STAYS. Once bills exists it is derivable
--     (MAX(period_end) per customer) and the two can drift. Keeping it as a
--     cached value is fine; it should stop being the idempotency guard, since
--     the unique index does that job properly. Not urgent, and not a reason to
--     hold up (a)-(d).
