-- 0071: setting up the ONU itself (Wi-Fi, internet login) over TR-069.
--
-- Apply with ispman-migrate. Until it runs, ISPMan sets nothing inside ONUs.
--
-- company_onu_config: each company's rules for its customers' ONUs —
--   {"enabled": true, "wifiName": "{first}-WiFi", "wifiPassword": "phone" | "account" | "random" | "leave",
--    "pppoe": true, "acs": {"zte": true, "vlan": 100}}
--   Wi-Fi name is a pattern filled from the customer; the password rule says
--   where it comes from; pppoe puts the customer's PPPoE login into the ONU.
--   acs.zte: point new ZTE-authorized ONUs at ISPMan's ACS through the OLT.
--
-- onu_acs: one row per ONU that has reached the ACS — when it was last seen,
-- what was sent to it and when. A generated Wi-Fi password is kept here so
-- staff can tell the customer; it is the customer's own Wi-Fi, not a login
-- to anything of the company's.

create table if not exists public.company_onu_config (
  company_id  BIGINT PRIMARY KEY REFERENCES public.companies(id) ON DELETE CASCADE,
  config      JSONB NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
alter table public.company_onu_config enable row level security;
drop policy if exists company_onu_config_company on public.company_onu_config;
create policy company_onu_config_company on public.company_onu_config
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

create table if not exists public.onu_acs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  serial        TEXT NOT NULL,
  device_id     TEXT,
  model         TEXT,
  last_seen     TIMESTAMPTZ,
  version       TEXT,
  sent_at       TIMESTAMPTZ,
  wifi_name     TEXT,
  wifi_password TEXT,
  unique (company_id, serial)
);
alter table public.onu_acs enable row level security;
drop policy if exists onu_acs_company on public.onu_acs;
create policy onu_acs_company on public.onu_acs
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
