-- 0066: changes ISPMan made to an OLT's own settings, with their undo.
--
-- Apply with ispman-migrate. Until this runs the OLT Settings tab can still
-- plan and make changes, but keeps no list of them and offers no Undo.
--
-- Each row is one change a person made from the OLT's Settings tab: what it
-- was in words, the exact commands sent, and the commands that put it back,
-- worked out from the OLT's state just before. Undo runs those and is itself
-- recorded, pointing back at the change it undid.

create table if not exists public.olt_changes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  olt_id      BIGINT NOT NULL REFERENCES public.olts(id) ON DELETE CASCADE,
  made_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  made_by     TEXT,
  summary     TEXT NOT NULL,
  commands    TEXT[] NOT NULL DEFAULT '{}',
  undo        TEXT[] NOT NULL DEFAULT '{}',
  undone_at   TIMESTAMPTZ,
  undo_of     BIGINT REFERENCES public.olt_changes(id) ON DELETE SET NULL
);
create index if not exists olt_changes_olt_idx on public.olt_changes (olt_id, made_at desc);

alter table public.olt_changes enable row level security;
drop policy if exists olt_changes_company on public.olt_changes;
create policy olt_changes_company on public.olt_changes
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
