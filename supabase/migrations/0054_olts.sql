-- 0054: OLTs a company runs, and how ISPMan reaches them.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this
-- table exists Network > OLTs says the feature is not set up.
--
-- ---------------------------------------------------------------------------
-- HOW ISPMAN REACHES AN OLT THAT HAS NO PUBLIC ADDRESS
--
-- An OLT sits on a private address behind one of the company's routers, and
-- that router is already on the tunnel. So ISPMan connects to the ROUTER, on a
-- port set aside for this OLT, and the router passes the connection on:
--
--   server -> 10.250.0.x : forward_port  --(router)-->  mgmt_ip : cli_port
--
-- NOT A ROUTE TO THE OLT'S OWN ADDRESS, deliberately. Two companies can both
-- have an OLT on 192.168.1.2 — private ranges are reused everywhere — and one
-- WireGuard interface cannot route the same address to two routers. A port on
-- the router's tunnel address is unique by construction, because the tunnel
-- address is.
--
-- The router side is two NAT rules and one firewall rule, added through
-- ISPMan's own login on that router (0052) and removed with the OLT. Every one
-- carries the comment "ISPMan OLT #<id>", so they can be found and removed
-- exactly, and so an owner reading their firewall can see what they are.
--
-- cli_secret and enable_secret HOLD CIPHERTEXT, the same AES-256-GCM as the
-- router logins, written and read only by lib/crypto.ts.
-- ---------------------------------------------------------------------------

create table if not exists public.olts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  -- The router this OLT sits behind. RESTRICT: removing the router would
  -- strand the OLT with no way to reach it, so the OLT goes first.
  tunnel_id     BIGINT NOT NULL REFERENCES public.router_tunnels(id) ON DELETE RESTRICT,
  name          TEXT NOT NULL,
  brand         TEXT NOT NULL DEFAULT 'zte',
  model         TEXT,
  mgmt_ip       TEXT NOT NULL,
  cli_protocol  TEXT NOT NULL DEFAULT 'telnet',
  cli_port      INTEGER NOT NULL DEFAULT 23,
  cli_user      TEXT NOT NULL,
  cli_secret    TEXT NOT NULL,
  enable_secret TEXT,
  -- The port on the router's tunnel address that leads to this OLT. Set once
  -- the row has an id, since it is derived from it.
  forward_port  INTEGER,
  forward_ok    BOOLEAN,
  checked_at    TIMESTAMPTZ,
  ok            BOOLEAN,
  error         TEXT,
  -- What the OLT said about itself at the last check: software version and the
  -- cards in each slot. Display only; nothing is decided from it.
  info          JSONB,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by    BIGINT
);

alter table public.olts drop constraint if exists olts_brand_check;
alter table public.olts add constraint olts_brand_check check (brand in ('zte'));
alter table public.olts drop constraint if exists olts_protocol_check;
alter table public.olts add constraint olts_protocol_check check (cli_protocol in ('telnet'));

create index if not exists olts_company_idx on public.olts (company_id);
create unique index if not exists olts_forward_port_idx
  on public.olts (tunnel_id, forward_port) where forward_port is not null;

comment on table public.olts is
  'OLTs a company runs. Reached through a forwarded port on the tunnel router they sit behind.';
comment on column public.olts.cli_secret is
  'AES-256-GCM ciphertext of the OLT login password (lib/crypto.ts). Never a readable password.';

alter table public.olts enable row level security;
drop policy if exists olts_company on public.olts;
create policy olts_company on public.olts
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
