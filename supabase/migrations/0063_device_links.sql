-- 0063: links — what is plugged into what.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this runs
-- the map shows ports and what is behind them, without chains.
--
-- THE NETWORK IS A CHAIN OF DEVICES, NOT A PORT AND A PLACE. The CCR's SFP
-- port feeds an edge switch, the switch powers a PowerBeam, that radio talks
-- to another PowerBeam, and that one feeds the Lacovia router. Each of those
-- joins is one row here: an upstream end (nearer the internet) and a
-- downstream end, each a router, an OLT or a device, with the port on each
-- side when known. This is how UISP and the other network tools model it
-- ("data links").
--
-- FOUND OR TYPED. A MikroTik announcing itself on a router port gives a link
-- automatically ('auto'). What sits silently in between — an unmanaged
-- switch, a pair of bridge radios — is invisible to discovery, so a person
-- inserts it into the chain ('manual'). An automatic link a person has split
-- is not put back.

create table if not exists public.device_links (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  up_type      TEXT NOT NULL,
  up_id        BIGINT NOT NULL,
  up_port      TEXT,
  down_type    TEXT NOT NULL,
  down_id      BIGINT NOT NULL,
  down_port    TEXT,
  medium       TEXT NOT NULL DEFAULT 'wired',
  source       TEXT NOT NULL DEFAULT 'manual',
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

alter table public.device_links drop constraint if exists device_links_type_check;
alter table public.device_links add constraint device_links_type_check
  check (up_type in ('router', 'olt', 'device') and down_type in ('router', 'olt', 'device'));
alter table public.device_links drop constraint if exists device_links_medium_check;
alter table public.device_links add constraint device_links_medium_check
  check (medium in ('wired', 'fiber', 'wireless'));
alter table public.device_links drop constraint if exists device_links_source_check;
alter table public.device_links add constraint device_links_source_check
  check (source in ('auto', 'manual'));

create index if not exists device_links_company_idx on public.device_links (company_id);
-- One link between the same two ends.
create unique index if not exists device_links_pair_idx
  on public.device_links (company_id, up_type, up_id, down_type, down_id);

-- Automatic links a person removed or split, so discovery does not put them
-- back on the next pass.
create table if not exists public.device_link_dismissed (
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  up_type     TEXT NOT NULL,
  up_id       BIGINT NOT NULL,
  down_type   TEXT NOT NULL,
  down_id     BIGINT NOT NULL,
  PRIMARY KEY (company_id, up_type, up_id, down_type, down_id)
);

alter table public.device_links enable row level security;
drop policy if exists device_links_company on public.device_links;
create policy device_links_company on public.device_links
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

alter table public.device_link_dismissed enable row level security;
drop policy if exists device_link_dismissed_company on public.device_link_dismissed;
create policy device_link_dismissed_company on public.device_link_dismissed
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
