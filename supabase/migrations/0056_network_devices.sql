-- 0056: every other device on a company's network.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this table
-- exists Network > Devices lists routers and OLTs only.
--
-- Routers live in router_tunnels and OLTs in olts, because ISPMan logs in to
-- those and each needs its own settings. This table is everything else a
-- network is made of — access points, customer radios, backhaul links,
-- switches — recorded so it can be seen in one place.
--
-- MOST ROWS ARE DISCOVERED, NOT TYPED. A router hears what the devices around
-- it announce about themselves, and ISPMan reads that list off the router.
-- found_via says which router heard it and found_on which port, so "where is
-- this thing" has an answer.
--
-- ONE ROW PER MAC ADDRESS PER COMPANY. Discovery is run again and again, and
-- the same radio must not be added twice. A device typed in by hand may have
-- no MAC and is not held to that.

create table if not exists public.network_devices (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  kind        TEXT NOT NULL DEFAULT 'other',
  name        TEXT NOT NULL,
  brand       TEXT,
  model       TEXT,
  ip          TEXT,
  mac         TEXT,
  version     TEXT,
  -- The router that heard this device, and the port it was heard on.
  found_via   BIGINT REFERENCES public.router_tunnels(id) ON DELETE SET NULL,
  found_on    TEXT,
  source      TEXT NOT NULL DEFAULT 'manual',
  notes       TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by  BIGINT
);

alter table public.network_devices drop constraint if exists network_devices_kind_check;
alter table public.network_devices add constraint network_devices_kind_check
  check (kind in ('router', 'olt', 'onu', 'ap', 'cpe', 'backhaul', 'switch', 'other'));
alter table public.network_devices drop constraint if exists network_devices_source_check;
alter table public.network_devices add constraint network_devices_source_check
  check (source in ('manual', 'discovered'));

create index if not exists network_devices_company_idx on public.network_devices (company_id);
-- Not a partial index: adding devices relies on "skip the ones already there",
-- which needs a plain unique index to name. Rows with no MAC are unaffected,
-- since two NULLs are never equal.
create unique index if not exists network_devices_mac_idx
  on public.network_devices (company_id, mac);

comment on table public.network_devices is
  'Access points, customer radios, backhauls, switches and other devices on a company network. '
  'Routers and OLTs have their own tables.';

alter table public.network_devices enable row level security;
drop policy if exists network_devices_company on public.network_devices;
create policy network_devices_company on public.network_devices
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
