-- 0058: watching ONUs between visits to the page.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until these
-- exist the background pass skips OLTs and everything else works as before.
--
-- Until now an OLT was only read when someone opened its page. These tables
-- let a background pass read every OLT every few minutes and notice what
-- changed since last time: an ONU that dropped, a whole PON port that went
-- dark, a signal that has fallen too low.
--
-- olt_onus          the last reading of each ONU. One row per ONU; replaced
--                   on every pass. "What changed" is this row compared with
--                   the new reading.
-- onu_signal_daily  one row per ONU per day: the weakest, strongest and
--                   latest signal that day. A fibre that is failing shows as
--                   a line that drifts down over weeks, long before it drops.
--
-- DAILY, NOT EVERY READING, for the same reason usage is daily (0053): a
-- reading every five minutes is 288 rows per ONU per day to answer a question
-- — "is this getting worse" — that one row a day answers.

create table if not exists public.olt_onus (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  olt_id         BIGINT NOT NULL REFERENCES public.olts(id) ON DELETE CASCADE,
  serial         TEXT NOT NULL,
  onu_ref        TEXT NOT NULL,
  port           TEXT NOT NULL,
  phase          TEXT,
  online         BOOLEAN NOT NULL DEFAULT false,
  rx             NUMERIC(6,2),
  tx             NUMERIC(6,2),
  -- Whether the low-signal alert has been raised for the current dip, so it is
  -- raised once and not on every pass.
  weak_alerted   BOOLEAN NOT NULL DEFAULT false,
  last_online_at TIMESTAMPTZ,
  offline_since  TIMESTAMPTZ,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

create unique index if not exists olt_onus_serial_idx on public.olt_onus (olt_id, serial);
create index if not exists olt_onus_company_idx on public.olt_onus (company_id, serial);

create table if not exists public.onu_signal_daily (
  olt_id     BIGINT NOT NULL REFERENCES public.olts(id) ON DELETE CASCADE,
  serial     TEXT NOT NULL,
  day        DATE NOT NULL,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  rx_min     NUMERIC(6,2),
  rx_max     NUMERIC(6,2),
  rx_last    NUMERIC(6,2),
  tx_last    NUMERIC(6,2),
  PRIMARY KEY (olt_id, serial, day)
);

create index if not exists onu_signal_daily_company_idx on public.onu_signal_daily (company_id, serial, day);

-- Let new ONUs on without anyone clicking. Off unless the owner turns it on:
-- anything plugged into the fibre would be given service.
alter table public.olts add column if not exists auto_authorise BOOLEAN NOT NULL DEFAULT false;

alter table public.olt_onus enable row level security;
drop policy if exists olt_onus_company on public.olt_onus;
create policy olt_onus_company on public.olt_onus
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

alter table public.onu_signal_daily enable row level security;
drop policy if exists onu_signal_daily_company on public.onu_signal_daily;
create policy onu_signal_daily_company on public.onu_signal_daily
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
