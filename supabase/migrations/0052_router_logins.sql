-- 0052: ISPMan gets its own login on each router, and a one-time link that
--       sets a router up in a single pasted line.
--
-- Apply in the Supabase dashboard (SQL Editor). Safe before or after the
-- deploy: until these columns exist, Add Router shows today's four-step paste
-- flow and nothing polls a router.
--
-- ---------------------------------------------------------------------------
-- WHY A ROUTER LOGIN AT ALL, WHEN RADIUS NEEDS NONE
--
-- RADIUS is the router talking to us. Everything in this migration is us
-- talking to the router, which RADIUS cannot do:
--
--   * Usage. A customer's data total lives in the simple queue's byte
--     counters on their router. It is NOT in radacct and never will be:
--     680,232 of our 680,248 accounting sessions carry zero octets, because
--     MikroTik's DHCP-server accounting records the lease, not the traffic —
--     the DHCP server is not in the traffic path and has nothing to count.
--     The 16 PPPoE sessions in the same table carry real counters, which is
--     the proof: the storage works, the routers simply have nothing to send.
--     So usage has to be read off the router.
--
--   * The firewall and masquerade rules that let us reach an OLT sitting
--     behind the router (0054).
--
-- ---------------------------------------------------------------------------
-- api_secret HOLDS CIPHERTEXT, NOT A PASSWORD
--
-- AES-256-GCM, keyed by ROUTER_SECRET_KEY in the environment, written and read
-- only by lib/crypto.ts. The column never holds a readable password, so a
-- leaked database row is not a router login, and nothing in the app prints one
-- — the same rule the WireGuard private key follows by never existing here at
-- all.
--
-- The password is generated by US, not chosen by the tenant: the setup script
-- creates the user with a password the server minted seconds earlier, so
-- nobody types it, nobody sees it, and it is already encrypted here before the
-- router has finished running the script.
--
-- api_kind IS NOT COSMETIC. Measured over the tunnel on 20 Nov 2026: eight of
-- ten routers answer the REST API on 80/8728, West Central's CCR1036 answers
-- only SSH, and one answers nothing at all. 10.250.0.9 returns 404 for /rest,
-- so it is on RouterOS 6 and needs the binary API. Three transports, chosen
-- per router, rather than one that works on most of them.
-- ---------------------------------------------------------------------------

alter table public.router_tunnels
  add column if not exists api_user       text,
  add column if not exists api_secret     text,
  add column if not exists api_kind       text not null default 'rest',
  add column if not exists api_port       integer,
  add column if not exists api_checked_at timestamptz,
  add column if not exists api_ok         boolean,
  add column if not exists api_error      text;

alter table public.router_tunnels
  drop constraint if exists router_tunnels_api_kind_check;
alter table public.router_tunnels
  add constraint router_tunnels_api_kind_check
  check (api_kind in ('rest', 'api', 'ssh'));

comment on column public.router_tunnels.api_secret is
  'AES-256-GCM ciphertext of the router password, written and read only by '
  'lib/crypto.ts under ROUTER_SECRET_KEY. Never a readable password.';
comment on column public.router_tunnels.api_kind is
  'How to reach this router: rest (RouterOS 7 HTTP), api (binary 8728, RouterOS 6), ssh.';
comment on column public.router_tunnels.api_error is
  'Why the last login attempt failed, in the operator''s words. Null when the last one worked.';

-- ---------------------------------------------------------------------------
-- router_setup_tokens: the one-time link behind the single pasted line
--
-- The line a tenant pastes fetches a RouterOS script from this link and runs
-- it. That script carries the tunnel address, the server's public key and
-- endpoint, the router's RADIUS secret and the password for the new ispman
-- user — so the link is as sensitive as all of those together, and is built to
-- be worth nothing a few minutes later:
--
--   ONE USE. used_at is stamped on the first fetch and a second fetch is
--   refused. A tenant who pastes the line twice gets a plain message and a
--   fresh link, rather than a token that works all week.
--
--   SHORT LIFE. expires_at, 30 minutes out. Long enough to walk to the router,
--   short enough that a line left in a chat log or a support ticket is dead.
--
--   HASHED, NOT STORED. token_hash holds sha256 of the token; the token itself
--   exists only in the line on the tenant's screen. A reader of this table
--   cannot mint the script, which matters because this table is the one place
--   that would otherwise collect every router's credentials in one list.
--
-- used_from records the address that fetched it, so an unexpected fetch is
-- visible after the fact rather than invisible.
--
-- WHY THE ROUTER REPORTS ITS OWN PUBLIC KEY. Today the owner copies the key
-- off the router and pastes it back into ISPMan — the step that makes this a
-- four-screen flow instead of one line. The script posts it back itself, to
-- the same token, which is the whole reason a single line can finish the job.
-- Nothing secret travels in that direction: a WireGuard public key is public,
-- and the private half still never leaves the router.
-- ---------------------------------------------------------------------------

create table if not exists public.router_setup_tokens (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  tunnel_id   BIGINT NOT NULL REFERENCES public.router_tunnels(id) ON DELETE CASCADE,
  token_hash  TEXT NOT NULL UNIQUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by  BIGINT,
  expires_at  TIMESTAMPTZ NOT NULL,
  used_at     TIMESTAMPTZ,
  used_from   TEXT,
  key_at      TIMESTAMPTZ
);

create index if not exists router_setup_tokens_tunnel_idx
  on public.router_setup_tokens (tunnel_id);

comment on table public.router_setup_tokens is
  'One-time, 30-minute links that serve a router its setup script. Single use, '
  'sha256-hashed, and the only route by which a router reports its public key.';
comment on column public.router_setup_tokens.key_at is
  'When the router posted its public key back. Null means the script ran but never got that far.';

alter table public.router_setup_tokens enable row level security;

-- Same shape as every other tenant table. Note what this policy deliberately
-- does NOT grant: the token itself is not in the table, so a tenant reading
-- every row of their own company still cannot rebuild a setup link.
drop policy if exists router_setup_tokens_company on public.router_setup_tokens;
create policy router_setup_tokens_company on public.router_setup_tokens
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

