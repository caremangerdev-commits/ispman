-- ISPMan: credits and discounts on a customer's account, for a stated period.
--
-- The case this is for: a customer was without service for 7 days in
-- November. A balance adjustment takes the money off, but says nothing about
-- which days it is for, so the bill can only fold it into "previous balance".
-- A credit is its own record: an amount, a reason and the period it covers, and
-- it prints on the bill as its own line, "No service 1–7 Nov  -J$816.67".
--
-- Lowers customers.carried_balance by the amount, through apply_customer_credit
-- so the balance and the record can never disagree. The balance either side is
-- stamped on the row, as on payments (0011) and bill_charges (0024), so the
-- bill can place it in the account's history.

CREATE TABLE IF NOT EXISTS public.customer_credits (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  customer_id  BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  amount       NUMERIC(10,2) NOT NULL,
  reason       TEXT NOT NULL,
  -- The service days it is for, both inclusive. Optional: a goodwill discount
  -- has no period.
  period_start DATE,
  period_end   DATE,
  -- The date it goes on the account, as the manager states it.
  credited_on  DATE NOT NULL DEFAULT CURRENT_DATE,
  carried_balance_before NUMERIC(12,2) NOT NULL,
  carried_balance_after  NUMERIC(12,2) NOT NULL,
  created_by_name TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT customer_credits_amount_check CHECK (amount > 0),
  CONSTRAINT customer_credits_reason_check CHECK (length(trim(reason)) > 0),
  CONSTRAINT customer_credits_period_check CHECK (
    (period_start IS NULL AND period_end IS NULL) OR
    (period_start IS NOT NULL AND period_end IS NOT NULL AND period_end >= period_start)
  )
);

CREATE INDEX IF NOT EXISTS customer_credits_customer_idx
  ON public.customer_credits (company_id, customer_id);

ALTER TABLE public.customer_credits ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS customer_credits_company ON public.customer_credits;
CREATE POLICY customer_credits_company ON public.customer_credits
  FOR ALL TO authenticated
  USING (company_id = public.current_company_id())
  WITH CHECK (company_id = public.current_company_id());

-- Lowers the balance and records the credit in one statement, the row locked
-- so a payment taken at the same moment cannot interleave.
CREATE OR REPLACE FUNCTION public.apply_customer_credit(
  p_company_id   BIGINT,
  p_customer_id  BIGINT,
  p_amount       NUMERIC,
  p_reason       TEXT,
  p_period_start DATE,
  p_period_end   DATE,
  p_credited_on  DATE,
  p_by_name      TEXT
) RETURNS public.customer_credits
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  v_before NUMERIC(12,2);
  v_row    public.customer_credits;
BEGIN
  SELECT COALESCE(carried_balance, 0) INTO v_before
    FROM public.customers
   WHERE company_id = p_company_id AND id = p_customer_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'customer % not found', p_customer_id;
  END IF;

  UPDATE public.customers
     SET carried_balance = v_before - ROUND(p_amount, 2)
   WHERE company_id = p_company_id AND id = p_customer_id;

  INSERT INTO public.customer_credits (
    company_id, customer_id, amount, reason, period_start, period_end, credited_on,
    carried_balance_before, carried_balance_after, created_by_name
  ) VALUES (
    p_company_id, p_customer_id, ROUND(p_amount, 2), trim(p_reason), p_period_start, p_period_end,
    COALESCE(p_credited_on, CURRENT_DATE), v_before, v_before - ROUND(p_amount, 2), p_by_name
  ) RETURNING * INTO v_row;

  RETURN v_row;
END;
$$;

REVOKE ALL ON FUNCTION public.apply_customer_credit(BIGINT, BIGINT, NUMERIC, TEXT, DATE, DATE, DATE, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.apply_customer_credit(BIGINT, BIGINT, NUMERIC, TEXT, DATE, DATE, DATE, TEXT) TO service_role;
