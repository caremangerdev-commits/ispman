-- 0061: sites — the places a network is built at.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this runs
-- the Sites page says it needs it, and every other page works as before.
--
-- A SITE IS A PLACE: a tower, a rooftop, the office, a cabinet. Routers, OLTs,
-- access points, switches and backhaul radios are put at one, so "what is on
-- the Retrieve tower" and "what goes down if Middle Quarters loses power" have
-- answers.
--
-- A BACKHAUL JOINS TWO SITES. The radio itself sits at one site and records
-- the site at the far end in links_to_site_id. The pair of radios on a link
-- can each be recorded, one at each end, pointing at the other.
--
-- Customer equipment (ONUs, customer radios) is not put at a site: a customer
-- is reached THROUGH a site, by the access point or OLT their equipment
-- connects to.

create table if not exists public.network_sites (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  kind        TEXT NOT NULL DEFAULT 'tower',
  notes       TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by  BIGINT
);

alter table public.network_sites drop constraint if exists network_sites_kind_check;
alter table public.network_sites add constraint network_sites_kind_check
  check (kind in ('tower', 'office', 'building', 'cabinet', 'other'));

create index if not exists network_sites_company_idx on public.network_sites (company_id);
create unique index if not exists network_sites_name_idx on public.network_sites (company_id, lower(name));

alter table public.network_sites enable row level security;
drop policy if exists network_sites_company on public.network_sites;
create policy network_sites_company on public.network_sites
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

alter table public.network_devices
  add column if not exists site_id BIGINT REFERENCES public.network_sites(id) ON DELETE SET NULL,
  add column if not exists links_to_site_id BIGINT REFERENCES public.network_sites(id) ON DELETE SET NULL;
alter table public.olts
  add column if not exists site_id BIGINT REFERENCES public.network_sites(id) ON DELETE SET NULL;
alter table public.router_tunnels
  add column if not exists site_id BIGINT REFERENCES public.network_sites(id) ON DELETE SET NULL;

create index if not exists network_devices_site_idx on public.network_devices (site_id);
