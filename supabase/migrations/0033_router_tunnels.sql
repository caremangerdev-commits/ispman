-- ISPMan: WireGuard tunnels for tenant routers — one row per router.
--
-- RUN THIS IN THE SUPABASE SQL EDITOR. Safe before or after the code: the code
-- probes for the table (lib/schema.ts, `routerTunnels`) and keeps the Router
-- Tunnels settings card hidden until it is present.
--
-- WHY (owner, 13 Oct 2026). Tenant routers sit on dynamic public IPs that
-- change about daily. A FreeRADIUS nas row keyed on a public IP goes stale the
-- next time the address moves, and the router falls onto the shared 0.0.0.0/0
-- catch-all — one client, one secret, one set of runtime state for every
-- router behind it. Three companies went dark in one week. Each router now
-- builds a WireGuard tunnel to the server and sends RADIUS through it from a
-- fixed inside address, which gets its own permanent nas row and secret.
-- Server half and rollout: docs/wireguard-tunnels.md.
--
-- ONE ROW PER ROUTER, NOT PER COMPANY. Smartcomm and Ezmze run several
-- routers, and WireGuard cannot share one key between two of them.
--
-- WHAT IS DELIBERATELY NOT HERE
--   - Any private key. The router generates its own key pair and keeps it;
--     ISPMan only ever sees the public key the owner pastes back.
--   - The RADIUS secret. It lives in the FreeRADIUS nas table, which is what
--     reads it. A second copy here could only drift from it.
--
-- ADDRESSES ARE NEVER REUSED. tunnel_ip is unique across revoked rows too, so
-- a revoked router's leftover config can never collide with a new router's.
-- The range is defined once, in lib/tunnels/wireguard.ts: 10.250.0.0/16 since
-- 13 Oct 2026 (it began as /24; nothing in this file depends on which).
--
-- ON DELETE RESTRICT on the company: deleting a company with live tunnels would
-- leave their nas rows behind in FreeRADIUS, answering for routers nobody owns.
-- Revoke them first; revoking removes the nas row.

CREATE TABLE IF NOT EXISTS public.router_tunnels (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id      BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE RESTRICT,
  name            TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 40),
  tunnel_ip       INET NOT NULL UNIQUE,
  -- NULL until the owner pastes the key the router generated (step 1 -> 2).
  public_key      TEXT UNIQUE,
  -- The RouterOS /radius services the tunnel entry carries: 'dhcp', 'dhcp,hotspot', ...
  services        TEXT NOT NULL DEFAULT 'dhcp',
  created_by      BIGINT,
  created_by_name TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  key_set_at      TIMESTAMPTZ,
  revoked_at      TIMESTAMPTZ,
  revoked_by      BIGINT
);

CREATE INDEX IF NOT EXISTS router_tunnels_company_idx
  ON public.router_tunnels (company_id);

ALTER TABLE public.router_tunnels ENABLE ROW LEVEL SECURITY;

-- Same shape as every other tenant table.
DROP POLICY IF EXISTS router_tunnels_company ON public.router_tunnels;
CREATE POLICY router_tunnels_company ON public.router_tunnels
  FOR ALL TO authenticated
  USING (company_id = public.current_company_id())
  WITH CHECK (company_id = public.current_company_id());

