-- 0062: how the network is wired, learned from the routers.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this runs
-- the Sites page shows no map and nothing is placed automatically.
--
-- network_ports: each port on each connected router, what was heard at the
-- other end of it (another MikroTik announces its name, model and the port
-- facing back), how many addresses sit behind it, and — the one thing a
-- person sets — which site it leads to.
--
-- mac_locations: which router port each MAC address was last seen behind.
-- Refreshed by the background pass. With ports mapped to sites, this places
-- every device and every customer at a site with nobody typing it.
--
-- network_devices.site_source: 'manual' when a person chose the site, which
-- the background pass never changes; 'auto' when the pass placed it.

create table if not exists public.network_ports (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id        BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  tunnel_id         BIGINT NOT NULL REFERENCES public.router_tunnels(id) ON DELETE CASCADE,
  port              TEXT NOT NULL,
  leads_to_site_id  BIGINT REFERENCES public.network_sites(id) ON DELETE SET NULL,
  neighbour_name    TEXT,
  neighbour_port    TEXT,
  neighbour_board   TEXT,
  neighbour_ip      TEXT,
  neighbour_mac     TEXT,
  macs_behind       INTEGER NOT NULL DEFAULT 0,
  seen_at           TIMESTAMPTZ
);
create unique index if not exists network_ports_port_idx on public.network_ports (tunnel_id, port);
create index if not exists network_ports_company_idx on public.network_ports (company_id);

alter table public.network_ports enable row level security;
drop policy if exists network_ports_company on public.network_ports;
create policy network_ports_company on public.network_ports
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

create table if not exists public.mac_locations (
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  tunnel_id   BIGINT NOT NULL REFERENCES public.router_tunnels(id) ON DELETE CASCADE,
  mac         TEXT NOT NULL,
  port        TEXT NOT NULL,
  seen_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tunnel_id, mac)
);
create index if not exists mac_locations_company_idx on public.mac_locations (company_id, mac);

alter table public.mac_locations enable row level security;
drop policy if exists mac_locations_company on public.mac_locations;
create policy mac_locations_company on public.mac_locations
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

alter table public.network_devices add column if not exists site_source TEXT;
alter table public.network_devices drop constraint if exists network_devices_site_source_check;
alter table public.network_devices add constraint network_devices_site_source_check
  check (site_source is null or site_source in ('auto', 'manual'));
