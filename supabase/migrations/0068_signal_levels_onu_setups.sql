-- 0068: each company's own signal levels per OLT and PON port, and its saved
-- ONU setups.
--
-- Apply with ispman-migrate. Until it runs, the usual levels (-25 dBm weak,
-- -27 dBm too low) apply everywhere and there are no saved setups.
--
-- olts.signal_levels: {"warn": -25, "critical": -27, "ports": {"gpon-olt_1/1/3": {"warn": -24, "critical": -26}}}
--   What counts as weak and too low on this OLT, and on any port that differs
--   (a long run, a port behind an extra splitter). Colours the ONU list and
--   decides the "low signal" alert.
--
-- onu_setups: named ways of setting an ONU up — tagged or untagged, the
-- VLANs, upload and download speed profiles — picked when authorizing or
-- applied to many ONUs at once.

alter table public.olts add column if not exists signal_levels JSONB;

create table if not exists public.onu_setups (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  setup       JSONB NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  unique (company_id, name)
);

alter table public.onu_setups enable row level security;
drop policy if exists onu_setups_company on public.onu_setups;
create policy onu_setups_company on public.onu_setups
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());
