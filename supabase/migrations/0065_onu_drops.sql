-- 0065: ONU drop history, PON outages, and incidents aimed at named customers.
--
-- Apply with ispman-migrate. Safe before or after the deploy: until this runs
-- the background check records nothing new and the pages show no history.
--
-- onu_drops: every time an ONU that was working is found not working, with
-- the cause the OLT gave (lost fibre signal, lost power, ...), when it came
-- back, and how many others on the same PON port went down in the same check.
-- That last number is what tells "this customer's ONU" from "the fibre to the
-- whole street".
--
-- pon_outages: a PON port that lost most of what was working on it at once,
-- with the ONUs and customers on it, so they can be told — and told again
-- when it is back.
--
-- incidents.scope 'customers': an incident for exactly the customers listed
-- in customer_ids, rather than the company or an access point. A PON outage
-- opens one of these.

create table if not exists public.onu_drops (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  olt_id       BIGINT NOT NULL REFERENCES public.olts(id) ON DELETE CASCADE,
  serial       TEXT NOT NULL,
  port         TEXT NOT NULL,
  customer_id  BIGINT,
  down_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  up_at        TIMESTAMPTZ,
  cause        TEXT,
  together     INTEGER NOT NULL DEFAULT 0
);
create index if not exists onu_drops_serial_idx on public.onu_drops (olt_id, serial, down_at desc);
create index if not exists onu_drops_company_idx on public.onu_drops (company_id, down_at desc);

alter table public.onu_drops enable row level security;
drop policy if exists onu_drops_company on public.onu_drops;
create policy onu_drops_company on public.onu_drops
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

create table if not exists public.pon_outages (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id    BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  olt_id        BIGINT NOT NULL REFERENCES public.olts(id) ON DELETE CASCADE,
  port          TEXT NOT NULL,
  started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at      TIMESTAMPTZ,
  serials       TEXT[] NOT NULL DEFAULT '{}',
  customer_ids  BIGINT[] NOT NULL DEFAULT '{}',
  incident_id   BIGINT REFERENCES public.incidents(id) ON DELETE SET NULL
);
create index if not exists pon_outages_olt_idx on public.pon_outages (olt_id, started_at desc);

alter table public.pon_outages enable row level security;
drop policy if exists pon_outages_company on public.pon_outages;
create policy pon_outages_company on public.pon_outages
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

-- Incidents for named customers.
do $$
declare c text;
begin
  for c in
    select con.conname from pg_constraint con
    join pg_class rel on rel.oid = con.conrelid
    where rel.relname = 'incidents' and con.contype = 'c'
      and pg_get_constraintdef(con.oid) ilike '%scope%'
  loop
    execute 'alter table public.incidents drop constraint ' || quote_ident(c);
  end loop;
end $$;
alter table public.incidents add constraint incidents_scope_check
  check (scope in ('company', 'access_point', 'customers'));
alter table public.incidents add column if not exists customer_ids BIGINT[];
