-- 0053: how much data each customer has used, read off their router.
--
-- Apply in the Supabase dashboard (SQL Editor). Safe before or after the
-- deploy: until these tables exist the poller does nothing and the customer
-- record shows no usage figure.
--
-- ---------------------------------------------------------------------------
-- WHY THIS CANNOT COME FROM RADIUS
--
-- It is the obvious place to look, and it is empty. Measured 20 Nov 2026:
--
--   680,248 accounting sessions in radacct, all time
--        81 of them carry any octets at all
--   680,232 are DHCP (a MAC as the username); 66 of those carry octets
--        16 are PPPoE (a name); 15 of those DO carry octets, up to 64 MB
--
-- The PPPoE rows are the control: when a router actually meters a session it
-- reports the counters, FreeRADIUS stores them, and they are there. MikroTik's
-- DHCP-server accounting records the LEASE, not the traffic — the DHCP server
-- hands out an address and is then no longer in the path, so it has nothing to
-- count. 15,154 DHCP sessions CLOSED this month and even their Accounting-Stop
-- carried zero bytes, which rules out interim updates as the fix.
--
-- So on a DHCP network the only per-customer meter is the simple queue on the
-- customer's own router, and the only way to read it is to log in and ask
-- (migration 0052). That is what fills these tables.
--
-- ---------------------------------------------------------------------------
-- TWO TABLES, BECAUSE A COUNTER IS NOT A MEASUREMENT
--
-- A simple queue's bytes field counts up from whenever the queue was created
-- or last reset, and goes back to zero when the router reboots. A reading on
-- its own therefore says nothing; only the difference between two readings is
-- usage. So:
--
--   usage_state holds the LAST READING per queue, and is overwritten every
--   poll. One row per queue — about 5,500 in total, not growing.
--
--   usage_daily holds the ACCUMULATED DIFFERENCES per customer per day, which
--   is the actual answer to "how much have they used". One row per customer
--   per day: roughly 5,500 a day, 165,000 a month.
--
-- WHY DAILY AND NOT EVERY FIVE MINUTES. 5,500 customers polled every five
-- minutes is 1.6 million rows a day, to answer questions nobody asks at that
-- resolution. A day is the unit a fair-use policy, a bill and a 30-day graph
-- all work in. Today's row is updated in place as the day goes on, so "used
-- so far today" is live without storing every sample.
--
-- A COUNTER GOING BACKWARDS IS A RESET, NOT NEGATIVE USAGE. The poller treats
-- a reading lower than the last one as a fresh start and counts the new
-- reading itself as the delta, which is the best available guess: the traffic
-- between the last poll and the reboot is genuinely lost, and the alternative
-- — a negative delta — would silently subtract from the month.
-- ---------------------------------------------------------------------------

create table if not exists public.usage_state (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  tunnel_id   BIGINT NOT NULL REFERENCES public.router_tunnels(id) ON DELETE CASCADE,
  -- The queue as the router names it. A queue can be renamed, so this is the
  -- address it serves, which is what the lease table matches on.
  target      TEXT NOT NULL,
  customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
  last_rx     BIGINT NOT NULL DEFAULT 0,
  last_tx     BIGINT NOT NULL DEFAULT 0,
  last_seen   TIMESTAMPTZ NOT NULL DEFAULT now(),
  resets      INTEGER NOT NULL DEFAULT 0
);

-- One row per queue per router. The upsert the poller runs needs this.
create unique index if not exists usage_state_queue_idx
  on public.usage_state (tunnel_id, target);

create index if not exists usage_state_customer_idx
  on public.usage_state (customer_id);

comment on table public.usage_state is
  'The last byte counters read from each simple queue, overwritten every poll. '
  'Only here to turn counters into differences; not a history.';
comment on column public.usage_state.resets is
  'How many times this queue''s counter has gone backwards. A high number means '
  'a router rebooting often, and usage under-counted by that much.';

create table if not exists public.usage_daily (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  -- The company's own date, not UTC: a day has to line up with the day the
  -- customer and the bill mean, the way the billing engine already works.
  day         DATE NOT NULL,
  rx_bytes    BIGINT NOT NULL DEFAULT 0,
  tx_bytes    BIGINT NOT NULL DEFAULT 0,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

create unique index if not exists usage_daily_customer_day_idx
  on public.usage_daily (customer_id, day);

-- The month-to-date figure on a customer record, and the company-wide reads.
create index if not exists usage_daily_company_day_idx
  on public.usage_daily (company_id, day);

comment on table public.usage_daily is
  'Bytes each customer used each day, accumulated from the differences between '
  'queue readings. rx is what the customer downloaded.';
comment on column public.usage_daily.day is
  'The company''s own date, from its timezone — the same day its bills mean.';

alter table public.usage_state enable row level security;
alter table public.usage_daily enable row level security;

-- Same shape as every other tenant table.
drop policy if exists usage_state_company on public.usage_state;
create policy usage_state_company on public.usage_state
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

drop policy if exists usage_daily_company on public.usage_daily;
create policy usage_daily_company on public.usage_daily
  for all to authenticated
  using (company_id = public.current_company_id())
  with check (company_id = public.current_company_id());

